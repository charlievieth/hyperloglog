func TestGenBeta(t *testing.T) {
	ezs := []float64{
		1,
		4,
		22,
		23,
		30,
		36,
		37,
		42,
		2438,
		4827,
		8297,
		8419,
		8778,
		8884,
		8890,
		8909,
	}
	for _, ez := range ezs {
		got := xbeta(ez)
		want := beta14(ez)
		delta := math.Abs(got - want)
		if delta > 0.000000001 {
			t.Errorf("beta14(%f) = %f; got %f | %.32f", ez, want, got, delta)
		}
	}
}

