type randombytes []byte

func (r randombytes) Bytes() []byte { return r }

func (r *randombytes) Next() []byte {
	for i, c := range *r {
		if c < 255 {
			(*r)[i]++
			return r.Bytes()
		}
	}
	*r = append(*r, 0)
	return r.Bytes()
}
