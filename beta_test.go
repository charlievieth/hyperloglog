func TestXBetaTests(t *testing.T) {
	for _, x := range betaTests {
		got := beta(x.P, float64(x.Ez))
		delta := math.Abs(got - x.Want)
		if delta > 1/1e9 {
			t.Errorf("beta(%d, %d) = %g; want: %g delta: %g",
				x.P, x.Ez, got, x.Want, delta)
		}
	}
}

